# Tests for `para expand` (tools/para/expandcmd.nim): reading the compiler's `--expandMacro` hints,
# counting written and generated lines, the size budget's verdict and the file it writes, all from
# canned compiler text; then one real run on the studio's desk (the same bytes twice, and a budget
# it is over is a finding). Nothing here reads a clock: the compile-time budget is
# .github/scripts/model-budget.sh's alone.

import std/[unittest, os, strutils]
import tools/para/expandcmd

const repoRoot = currentSourcePath().parentDir.parentDir

const desk = "/w/tools/para/desk.nim"
const cannedOutput = """Hint: used config file '/w/config.nims' [Conf]
/w/tools/para/other.nim(3, 1) Hint: expanded macro: type
  Elsewhere* = object [ExpandMacro]
/w/tools/para/desk.nim(2, 1) Hint: expanded macro: type
  Thing* = object
    name*: string [ExpandMacro]
/w/tools/para/desk.nim(5, 1) Hint: expanded macro:
proc fold(v: var V) =
  discard [ExpandMacro]
/w/tools/para/desk.nim(9, 1) Hint: expanded macro: sealed(Desk) [ExpandMacro]
/w/tools/para/desk.nim(10, 3) Warning: imported and not used: 'os' [UnusedImport]
Hint:
100 lines; 0.4s; 170MiB peakmem; proj: /w/tools/para/desk.nim; out: unknownOutput [SuccessX]
"""
const deskSource = "import eversince\nrecord Thing:\n  name: string\n\nview V:\n  on x\n\n\nsealModel(Desk, \"desk.em\")\n"

suite "reading the compiler's expansions":
  let exps = parseExpansions(cannedOutput, desk)

  test "only the file's own blocks, in order, with the line each starts on":
    check exps.len == 3
    check exps[0].line == 2
    check exps[1].line == 5
    check exps[2].line == 9

  test "the code is what the compiler printed, without the hint's frame":
    check exps[0].code == "type\n  Thing* = object\n    name*: string"
    check exps[1].code == "proc fold(v: var V) =\n  discard"   # the empty rest of the hint line is dropped
    check exps[2].code == "sealed(Desk)"                         # an expansion on one line

  test "a hint of another module, a warning and the summary are not expansions":
    for e in exps: check "Elsewhere" notin e.code and "SuccessX" notin e.code and "UnusedImport" notin e.code
    check parseExpansions(cannedOutput, "/w/tools/para/none.nim").len == 0
    check parseExpansions("", desk).len == 0

suite "the size and its budget":
  test "lines are counted the way wc counts a file, plus a last line without its newline":
    check lineCount("") == 0
    check lineCount("a") == 1
    check lineCount("a\n") == 1
    check lineCount("a\nb") == 2
    check lineCount("a\n\nb\n") == 3

  test "written is the file's lines, generated the expansions' lines":
    let s = measure(deskSource, parseExpansions(cannedOutput, desk))
    check s.written == 9
    check s.generated == 3 + 2 + 1
    check ratioText(s.ratio) == "0.67"

  test "the ratio as printed is what the budget judges: equal is within, over is a finding":
    let today = ExpandSize(written: 1244, generated: 1701)   # the studio's desk when the budget was set
    check ratioText(today.ratio) == "1.37"
    check not today.overBudget(1.5)
    check not today.overBudget(1.37)
    check today.overBudget(1.36)
    check ExpandSize(written: 2, generated: 3).overBudget(1.49)
    check not ExpandSize(written: 0, generated: 0).overBudget(0.01)

suite "the file it writes":
  let exps = parseExpansions(cannedOutput, desk)
  let text = expandedText("tools/para/desk.nim", deskSource, exps)

  test "sits beside the module as <module>.expanded.nim":
    check expandedPath("tools/para/studiodesk.nim") == "tools/para/studiodesk.expanded.nim"

  test "says where it came from, not to edit it, and its size":
    check text.startsWith("# Generated by `para expand` from tools/para/desk.nim")
    check "never edit or import it" in text
    check "# written 9 lines, generated 6 lines, ratio 0.67\n" in text

  test "heads each expansion with its line in the module":
    check "\n# tools/para/desk.nim:2  record Thing:\ntype\n  Thing* = object\n    name*: string\n" in text
    check "\n# tools/para/desk.nim:5  view V:\nproc fold" in text
    check "\n# tools/para/desk.nim:9  sealModel(Desk, \"desk.em\")\nsealed(Desk)\n" in text

  test "is a function of its inputs":
    check expandedText("tools/para/desk.nim", deskSource, exps) == text

suite "para expand: flags":
  test "--help, exit 0":
    let r = runExpand(@["--help"])
    check r.code == 0
    check r.output.startsWith("para expand")

  test "usage errors exit 2":
    check runExpand(@["--bogus"]).code == 2
    check runExpand(@["--max-ratio"]).code == 2
    check runExpand(@["--max-ratio", "lots"]).code == 2
    check runExpand(@["--max-ratio", "0"]).code == 2
    check runExpand(@["--max-ratio", "nan"]).code == 2
    check runExpand(@["--max-ratio", "inf"]).code == 2
    check runExpand(@["--max-ratio", "-inf"]).code == 2
    check runExpand(@[defaultSource]).code == 2
    check runExpand(@["--out", "x.nim"]).code == 2

suite "para expand: the studio's desk, for real":
  setCurrentDir(repoRoot)
  let written = expandedPath(defaultSource)

  test "writes every block's expansion beside the model file, the same bytes each run":
    let r = runExpand(@[])
    check r.code == 0
    check r.output.startsWith("expand: wrote " & written)
    check r.output.contains("size[1]{file,blocks,written,generated,ratio}:")
    var calls = 0
    for line in readFile(defaultSource).splitLines:
      for m in blockMacros:
        if line.startsWith(m & " ") or line.startsWith(m & "("): inc calls
    let text = readFile(written)
    check text.count("\n# " & defaultSource & ":") == calls
    for m in ["record", "event", "command", "view", "query", "processor", "sealModel"]:
      check ("  " & m) in text
    check runExpand(@[]).code == 0
    check readFile(written) == text

  test "a ratio over the budget is a finding, exit 1":
    let r = runExpand(@["--max-ratio", "0.5"])
    check r.code == 1
    check "is over the budget of 0.50" in r.output
